<?php
/**
 * Hardened root download.php for AllxSys / phpNuxBill-style panels.
 *
 * Replaces a broken production download.php that returned HTTP 500 with an
 * empty body (Live mode: display_errors=0).
 *
 * Supports:
 *   /download.php?preview=1
 *   /download.php?preview=1&id=<router_id>
 *   /download.php?preview=1&router=<router_name>
 *
 * Upload to document root (same folder as index.php). Backup the old file first.
 */

declare(strict_types=1);

$__dl_log = __DIR__ . '/system/cache/download-php-error.log';
@ini_set('log_errors', '1');
@ini_set('error_log', $__dl_log);
error_reporting(E_ALL);
$__debug = isset($_GET['debug']) && $_GET['debug'] === '1';
@ini_set('display_errors', $__debug ? '1' : '0');

register_shutdown_function(static function () use ($__debug, $__dl_log) {
    $e = error_get_last();
    if (!$e || !in_array($e['type'], [E_ERROR, E_PARSE, E_CORE_ERROR, E_COMPILE_ERROR], true)) {
        return;
    }
    $msg = sprintf("download.php FATAL: %s in %s:%d", $e['message'], $e['file'], $e['line']);
    @file_put_contents($__dl_log, date('c') . ' ' . $msg . "\n", FILE_APPEND);
    if (!headers_sent()) {
        header('HTTP/1.1 500 Internal Server Error');
        header('Content-Type: text/plain; charset=utf-8');
    }
    echo $__debug
        ? $msg
        : "download.php failed. Open /download.php?preview=1&debug=1 or check system/cache/download-php-error.log";
});

try {
    download_main();
} catch (Throwable $t) {
    @file_put_contents(
        $__dl_log,
        date('c') . ' download.php THROW: ' . $t->getMessage() . ' @ ' . $t->getFile() . ':' . $t->getLine() . "\n",
        FILE_APPEND
    );
    if (!headers_sent()) {
        header('HTTP/1.1 500 Internal Server Error');
        header('Content-Type: text/plain; charset=utf-8');
    }
    echo $__debug
        ? ('THROW: ' . $t->getMessage() . "\n" . $t->getFile() . ':' . $t->getLine())
        : 'download.php failed (see system/cache/download-php-error.log). Add &debug=1';
    exit;
}

function download_main(): void
{
    $preview = isset($_GET['preview']) && (string)$_GET['preview'] !== '' && (string)$_GET['preview'] !== '0';

    // Prefer existing controller if present (AllxSys custom).
    $controller = __DIR__ . '/system/controllers/download.php';
    $plugin = __DIR__ . '/system/plugin/download.php';

    if (is_file(__DIR__ . '/init.php')) {
        require_once __DIR__ . '/init.php';
    } elseif (is_file(__DIR__ . '/system/boot.php')) {
        require_once __DIR__ . '/system/vendor/autoload.php';
        require_once __DIR__ . '/system/boot.php';
    } else {
        throw new RuntimeException('Panel bootstrap not found (init.php / system/boot.php).');
    }

    // If a dedicated controller exists, hand off with routes compatible with phpNuxBill.
    if (is_file($controller)) {
        global $routes, $ui, $admin, $config;
        if (!isset($routes) || !is_array($routes)) {
            $routes = [];
        }
        $routes[0] = 'download';
        $routes[1] = $preview ? 'preview' : (isset($_GET['type']) ? (string)$_GET['type'] : 'list');
        if (isset($_GET['id'])) {
            $routes[2] = (string)$_GET['id'];
        }
        include $controller;
        return;
    }

    if (is_file($plugin)) {
        include $plugin;
        return;
    }

    // Fallback: preview MikroTik API reachability helper script from tbl_routers.
    if (!class_exists('ORM', false)) {
        throw new RuntimeException('ORM not loaded after bootstrap; cannot build preview.');
    }

    $router = null;
    if (!empty($_GET['id'])) {
        $router = ORM::for_table('tbl_routers')->find_one((int)$_GET['id']);
    } elseif (!empty($_GET['router'])) {
        $router = ORM::for_table('tbl_routers')->where('name', (string)$_GET['router'])->find_one();
    } else {
        $router = ORM::for_table('tbl_routers')->where('enabled', '1')->order_by_desc('id')->find_one();
    }

    if (!$router) {
        header('Content-Type: text/plain; charset=utf-8');
        echo "No router found. Add routers under Network → Routers, then reopen download.php?preview=1&id=<id>\n";
        return;
    }

    $name = (string)$router['name'];
    $ip = (string)$router['ip_address'];
    $user = (string)$router['username'];
    $script = "; MWANIKI / AllxSys — API helper for router: {$name}\n"
        . "; Generated by hardened download.php — paste in Winbox Terminal if needed\n"
        . "; Ensure API is reachable from the billing VPS (public IP or VPN tunnel).\n\n"
        . "/ip service\n"
        . "set api disabled=no port=8728\n"
        . "set winbox disabled=no\n\n"
        . "/ip firewall filter\n"
        . "add chain=input protocol=tcp dst-port=8728 action=accept comment=\"Allow billing API\" place-before=0\n\n"
        . "; Panel connection target for this router:\n"
        . ";   Address: {$ip}\n"
        . ";   User: {$user}\n"
        . ";   Name in panel: {$name}\n";

    if ($preview) {
        header('Content-Type: text/plain; charset=utf-8');
        echo $script;
        return;
    }

    header('Content-Type: application/octet-stream');
    header('Content-Disposition: attachment; filename="' . preg_replace('/[^a-zA-Z0-9_-]+/', '_', $name) . '-api.rsc"');
    echo $script;
}
